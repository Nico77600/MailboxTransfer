#Requires -Version 7.4
<#
.SYNOPSIS
    Lists the files that the owner signs (Authenticode) before a release, and puts them in the form the signature needs.

.DESCRIPTION
    The files to sign are every PowerShell file of package\ (.ps1, .psm1, .psd1) except the editable configuration of
    package\config\ and except PackageIntegrity.psd1, which is signed last, after its hashes are generated by
    tools\New-PackageIntegrity.ps1. For each file the script checks the form the signature procedure needs: ASCII only,
    no byte order mark, CRLF line ends, a final line end, and writes the inventory (Path, Bytes, Sha256) that the
    procedure shows to the owner and compares with the staged Git blobs (scripts\Test-SignedGitBytes.ps1).

    The script never signs, never timestamps and never contacts a service.

.PARAMETER Normalize
    Rewrites the files that are not in the form above (CRLF, no BOM) before listing them. A non-ASCII character is not
    rewritten: it stops the script, because Windows PowerShell 5.1 would read it differently from PowerShell 7.

.PARAMETER OutputPath
    Where to write the inventory (JSON). Default: no file, the inventory is returned.

.EXAMPLE
    .\tools\Get-SigningInventory.ps1 -Normalize -OutputPath ..\MailboxTransfer-signing\inventory-unsigned.json

.NOTES
    Author  : Nicolas Fabert
    Version : 1.0.0
#>
[CmdletBinding()]
param([switch]$Normalize, [string]$OutputPath)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$package = Join-Path $root 'package'
$files = @(Get-ChildItem -LiteralPath $package -Recurse -File -Include *.ps1, *.psm1, *.psd1 |
    Where-Object { $_.FullName -notlike (Join-Path $package 'config\*') -and $_.Name -ne 'PackageIntegrity.psd1' } |
    Sort-Object { $_.FullName.ToLowerInvariant() })
if (-not $files) { throw 'No PowerShell file in package\.' }

$problems = [Collections.Generic.List[string]]::new()
$inventory = foreach ($file in $files) {
    $relative = 'package\' + [IO.Path]::GetRelativePath($package, $file.FullName)
    $bytes = [IO.File]::ReadAllBytes($file.FullName)
    $hasBom = $bytes.Length -ge 3 -and $bytes[0] -eq 0xEF -and $bytes[1] -eq 0xBB -and $bytes[2] -eq 0xBF
    $text = [Text.UTF8Encoding]::new($false).GetString($bytes, $(if ($hasBom) { 3 } else { 0 }), $bytes.Length - $(if ($hasBom) { 3 } else { 0 }))
    $nonAscii = [regex]::Match($text, '[^\x00-\x7F]')
    if ($nonAscii.Success) { $problems.Add("$relative has a non-ASCII character at offset $($nonAscii.Index) (U+{0:X4}); replace it before signing." -f [int][char]$nonAscii.Value) }
    $lf = $text.Replace("`r`n", "`n")
    $wanted = ($lf.TrimEnd("`n") + "`n").Replace("`n", "`r`n")
    if ($text -cne $wanted -or $hasBom) {
        if ($Normalize -and -not $nonAscii.Success) {
            [IO.File]::WriteAllBytes($file.FullName, [Text.UTF8Encoding]::new($false).GetBytes($wanted))
            $bytes = [IO.File]::ReadAllBytes($file.FullName)
        } elseif (-not $nonAscii.Success) {
            $problems.Add("$relative is not CRLF without BOM (run with -Normalize).")
        }
    }
    [ordered]@{
        Path   = $relative
        Bytes  = $bytes.Length
        Sha256 = (Get-FileHash -LiteralPath $file.FullName -Algorithm SHA256).Hash
    }
}
if ($problems.Count) { throw ("Not ready to sign:`n - " + ($problems -join "`n - ")) }
$json = ConvertTo-Json -InputObject @($inventory) -Depth 3
if ($OutputPath) {
    [void][IO.Directory]::CreateDirectory((Split-Path ([IO.Path]::GetFullPath($OutputPath)) -Parent))
    [IO.File]::WriteAllText([IO.Path]::GetFullPath($OutputPath), $json, [Text.UTF8Encoding]::new($false))
}
Write-Host ('{0} files to sign.' -f @($inventory).Count)
$inventory | ForEach-Object { [pscustomobject]$_ }
