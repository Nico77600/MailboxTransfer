#Requires -Version 7.4
<#
    Mailbox Transfer - EML export and import (functions of the module, dot-sourced by MailboxTransfer.psm1).

        Export-MbtEml    a mailbox (Mail API $value), an export store or a PST  ->  a directory tree of .eml files + manifest.jsonl
        Import-MbtEml    a directory tree of .eml files  ->  folders of a mailbox (own MIME conversion + FastTransfer + importItem,
                         or -MimeConversion Exchange: Exchange converts through a draft)
        Compare-MbtEml   two .eml files: headers, structure, text bodies and attachment hashes

    The engine is in src\Engine.Mime.cs (parser, writer), Engine.EmlMapi.cs (MIME <-> MAPI), Engine.Eml.cs (export, comparison),
    Engine.EmlImport.cs (import).
#>

function Export-MbtEml {
    <#
    .SYNOPSIS
        Exports messages as .eml files: the folder tree becomes a directory tree, one .eml per message, manifest.jsonl (id, folder, file,
        subject, size, SHA-256, dates, state). Resumable (run it again: what is in the manifest with its file in place is not read again).
    .DESCRIPTION
        -Location (Live): a browse location of Primary or Archive; the messages are read with the Mail API (GET .../messages/{id}/$value,
        delegated Mail.Read), so the .eml is Exchange's own MIME. An auxiliary archive is not reachable: export it to a store or a PST first.
        -Store: an export store (FastTransfer streams), -PstPath: a PST (any location): the MIME is built from the MAPI properties.
        Items that are not messages (appointments, contacts, tasks...) and non-mail folders are reported in the result and the manifest, not exported.
        -WhatIf lists what would be written and writes nothing.
    #>
    [CmdletBinding(SupportsShouldProcess, DefaultParameterSetName = 'Live')]
    param(
        [Parameter(Mandatory)][string]$OutputPath,
        [Parameter(Mandatory, ParameterSetName = 'Live')]$Location,
        [Parameter(Mandatory, ParameterSetName = 'Store')]$Store,
        [Parameter(ParameterSetName = 'Store')][string]$MailboxId,
        [Parameter(Mandatory, ParameterSetName = 'Pst')][string]$PstPath,
        [string]$Folder,
        [ValidateRange(1, 4)][int]$Concurrency = 4,
        [switch]$NoResume,
        [switch]$NoTransportHeaders,
        [int]$ProgressSeconds = 5,
        [Threading.CancellationToken]$CancellationToken = [Threading.CancellationToken]::None
    )
    Initialize-MbtEngine
    $reader = $null
    try {
        $source = switch ($PSCmdlet.ParameterSetName) {
            'Live' { [MailboxTransfer.LiveEmlSource]::new((Get-MbtBrowser -NoNonMailFolders), $Location) }
            'Store' { [MailboxTransfer.StoreEmlSource]::new($Store, $(if ($MailboxId) { $MailboxId } else { $null })) }
            'Pst' { $reader = [MailboxTransfer.PstReader]::Open($PstPath); [MailboxTransfer.PstEmlSource]::new($reader, [IO.Path]::GetFileNameWithoutExtension($PstPath)) }
        }
        if ($source -is [MailboxTransfer.MapiEmlSource]) { $source.Mime.UseTransportHeaders = -not $NoTransportHeaders }
        $o = [MailboxTransfer.EmlExportOptions]::new()
        $o.OutputDirectory = if ([IO.Path]::IsPathRooted($OutputPath)) { $OutputPath } else { Join-Path (Get-Location).Path $OutputPath }
        $o.WhatIf = -not $PSCmdlet.ShouldProcess($o.OutputDirectory, "Write .eml files from $($source.Description)")
        $o.Resume = -not $NoResume
        $o.Concurrency = $Concurrency
        $o.Cancellation = $CancellationToken
        $o.Progress = [MailboxTransfer.ConsoleProgress]::new($ProgressSeconds)
        if ($Folder) {
            $prefix = $Folder.Trim('/', '\').Replace('\', '/')
            $o.FolderFilter = [Func[string, bool]]{ param($p) $p -ieq $prefix -or $p.StartsWith($prefix + '/', [StringComparison]::OrdinalIgnoreCase) }.GetNewClosure()
        }
        Write-MbtItem INFO ("exporting {0} to {1}{2}" -f $source.Description, $o.OutputDirectory, $(if ($o.WhatIf) { ' (WhatIf: nothing is written)' }))
        # with an event log open (a job of the console) the folders are followed: the Run page lists them
        $follow = Start-MbtFolderEvents -Step export -StepEvents
        if ($follow) { $o.Folders = $follow.Tracker }
        try { return [MailboxTransfer.EmlExporter]::Run($source, $o) }
        finally { Stop-MbtFolderEvents $follow }
    } finally { if ($reader) { $reader.Dispose() } }
}

function Import-MbtEml {
    <#
    .SYNOPSIS
        Creates messages in a mailbox from .eml files (a directory tree, or one file), below the top-level folder -TargetRoot. Create only.
    .DESCRIPTION
        -MimeConversion Own (default): this tool's MIME parser builds the MAPI message, sent as a FastTransfer stream to importItem. No extra
        permission; works for every location, auxiliary archives included. The received time comes from the manifest of an export, else the
        X-MailboxTransfer-Received header, else the first Received header, else Date.
        -MimeConversion Exchange: Exchange converts the MIME: a draft is created with the Mail API (needs the delegated permission Mail.ReadWrite),
        exported, patched (not a draft, read state, received time), imported, and the draft is deleted.
        -IncludeFolder / -ExcludeFolder: only some folders (paths below the import folder, wildcards * and ?; a path chooses the folder and what is below it,
        an exclusion wins). The files of the other folders are left out and counted (Filtered).
        Resumable: import-state.jsonl (in the import folder, or -StatePath). -WhatIf lists the files and creates nothing.
    #>
    [CmdletBinding(SupportsShouldProcess)]
    param(
        [Parameter(Mandatory)][string]$Path,
        [Parameter(Mandatory)][string]$MailboxId,
        [Parameter(Mandatory)][string]$TargetRoot,
        [ValidateSet('Own', 'Exchange')][string]$MimeConversion = 'Own',
        [switch]$Unread,
        [switch]$NoResume,
        [string[]]$IncludeFolder,
        [string[]]$ExcludeFolder,
        [string]$StatePath,
        [int]$ProgressSeconds = 5,
        [Threading.CancellationToken]$CancellationToken = [Threading.CancellationToken]::None
    )
    Initialize-MbtEngine
    $s = Get-MbtSession
    $run = [MailboxTransfer.EmlImportRun]::new()
    $run.Path = (Resolve-Path -LiteralPath $Path).Path
    $run.Api = $s.Api
    $run.MailboxId = $MailboxId
    $run.TargetRoot = $TargetRoot
    $run.WhatIf = -not $PSCmdlet.ShouldProcess("$MailboxId folder $TargetRoot", "Create messages from $($run.Path)")
    $run.Resume = -not $NoResume
    $run.Unread = [bool]$Unread
    foreach ($f in @($IncludeFolder | Where-Object { $_ })) { $run.IncludeFolders.Add($f) }
    foreach ($f in @($ExcludeFolder | Where-Object { $_ })) { $run.ExcludeFolders.Add($f) }
    if ($StatePath) { $run.StatePath = $StatePath }
    $run.Cancellation = $CancellationToken
    $run.Progress = [MailboxTransfer.ConsoleProgress]::new($ProgressSeconds)
    if ($MimeConversion -eq 'Exchange') {
        $run.Conversion = [MailboxTransfer.EmlConversion]::Exchange
        if ($s.Token -and -not ('Mail.ReadWrite' -in $s.Token.Scopes)) {
            throw "-MimeConversion Exchange creates a draft with the Mail API and needs the $(if (Test-MbtAppOnly $s) { 'application' } else { 'delegated' }) permission Mail.ReadWrite, which is not in the token (permissions: $($s.Token.Scopes -join ' ')). Grant it to the application (not done by this tool) or use -MimeConversion Own."
        }
        $run.Exchange = [MailboxTransfer.EmlExchangeConverter]::new($s.Api, $MailboxId, $MailboxId)
    }
    Write-MbtItem INFO ("importing {0} into {1} below '{2}' ({3} conversion){4}" -f $run.Path, $MailboxId, $TargetRoot, $MimeConversion, $(if ($run.WhatIf) { ' (WhatIf: nothing is created)' }))
    $follow = Start-MbtFolderEvents -Step send -StepEvents
    if ($follow) { $run.Folders = $follow.Tracker }
    try { return [MailboxTransfer.EmlImporter]::Run($run) }
    finally { Stop-MbtFolderEvents $follow }
}

function Resolve-MbtEmlUnknown {
    <#
    .SYNOPSIS
        Settles the .eml files an import left Unknown (the request may have created the item: a timeout, a 5xx, an answer that could not be read, a run stopped or killed inside the request).
    .DESCRIPTION
        An Unknown file is never imported again by itself. After looking in the mailbox: -As Imported (the item is there: the file becomes Done) or -As NotImported (it is not: the file becomes
        Failed and the next run imports it). -File: the files as the state lists them (relative paths); without it every Unknown file of the state. Appends to import-state.jsonl; returns the files settled.
    #>
    [CmdletBinding(SupportsShouldProcess)]
    param(
        [Parameter(Mandatory)][string]$Path,
        [Parameter(Mandatory)][ValidateSet('Imported', 'NotImported')][string]$As,
        [string[]]$File,
        [string]$StatePath
    )
    Initialize-MbtEngine
    if (-not $StatePath) {
        $item = Get-Item -LiteralPath $Path
        $StatePath = Join-Path $(if ($item.PSIsContainer) { $item.FullName } else { $item.DirectoryName }) ([MailboxTransfer.EmlImporter]::StateName)
    }
    if (-not (Test-Path -LiteralPath $StatePath)) { throw "No import state at ${StatePath}: nothing to settle." }
    if (-not $PSCmdlet.ShouldProcess($StatePath, "Settle the Unknown files as $As")) { return @() }
    return @([MailboxTransfer.EmlImporter]::Resolve($StatePath, ($As -eq 'Imported'), $(if ($File) { [string[]]$File })))
}

function Compare-MbtEml {
    <# Compares two .eml files (or byte arrays): headers, structure, text bodies, attachment hashes. Returns the comparison (.Items, .Differences, .ContentEqual, .Identical). #>
    [CmdletBinding()]
    param([Parameter(Mandatory)]$Left, [Parameter(Mandatory)]$Right)
    Initialize-MbtEngine
    $l = if ($Left -is [byte[]]) { $Left } else { [IO.File]::ReadAllBytes((Resolve-Path -LiteralPath $Left).Path) }
    $r = if ($Right -is [byte[]]) { $Right } else { [IO.File]::ReadAllBytes((Resolve-Path -LiteralPath $Right).Path) }
    return [MailboxTransfer.EmlCompare]::Compare($l, $r)
}

